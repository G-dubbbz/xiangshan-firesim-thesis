// XSTopBlackBox.scala
//
// Verilog-blackbox wrapper for XiangShan's generated `XSTop` module.
//
// Source of truth: a FULL, unfiltered port dump of the actual IDUN-built
// `build/rtl/XSTop.sv` (2026-09-21, `grep -nE '^\s*(input|output)'`,
// 165 port lines total, lines 77-241 of a 1133-line file — this is
// EVERY port, not a filtered subset). Every port below is [CONFIRMED]
// against that dump. See `xiangshan-baseline.md` in the "Project thesis"
// Claude Project for the full history — two earlier guesses at the AXI4
// naming convention were wrong (an `io_memory_*`/bits_-hierarchy guess
// from a differently-generated XSTop.sv, and a bare-`io_` prefix
// assumption); this version is transcribed directly from the real file,
// not inferred.
//
// Key corrections vs. earlier drafts:
//   - AXI4 ports have NO `io_` prefix at all: literally `memory_*`,
//     `peripheral_*`, `dma_*`, sitting outside the `io` bundle XiangShan
//     uses for everything else.
//   - AXI4 field names are flat AXI-standard short names with no `bits_`
//     hierarchy and no separate `aw_`/`w_`/etc. underscore: e.g.
//     `memory_awvalid`, `memory_awid`, `memory_awaddr` — not
//     `memory_aw_valid`/`memory_aw_bits_id`.
//   - Clock/reset are `io_clock`/`io_reset` (not bare `clock`/`reset` —
//     Chisel BlackBox has no automatic clock/reset port unlike Module).
//
// Run this any time this file needs re-validation against a fresh build:
//   grep -nE '^\s*(input|output)' build/rtl/XSTop.sv

package xiangshan

import chisel3._
import chisel3.util._

/** Flat AXI4 bundle matching XSTop's literal Verilog naming: field names
  * are the bare AXI signal names (`awvalid`, `awid`, `awaddr`, ...), and
  * the enclosing `val` name (`memory`/`peripheral`/`dma`) becomes the
  * Verilog port prefix via Chisel's Bundle-instance flattening, giving
  * `memory_awvalid` etc. — confirmed byte-for-byte against XSTop.sv.
  *
  * `master = true`: XSTop is the AXI4 master (`memory_*`, `peripheral_*`)
  * — aw/w/ar request-side fields are Outputs, ready/b/r response-side
  * fields are Inputs. `master = false`: XSTop is the AXI4 slave (`dma_*`)
  * — every direction flips.
  */
class XSTopAXI4Port(addrW: Int, dataW: Int, idW: Int, master: Boolean) extends Bundle {
  private def out(width: Int = -1): Data = if (master) reqDir(width) else respDir(width)
  private def in(width: Int = -1): Data  = if (master) respDir(width) else reqDir(width)
  private def reqDir(width: Int): Data  = if (width < 0) Output(Bool()) else Output(UInt(width.W))
  private def respDir(width: Int): Data = if (width < 0) Input(Bool())  else Input(UInt(width.W))

  // Write address channel
  val awvalid = out()
  val awready = in()
  val awid    = out(idW)
  val awaddr  = out(addrW)
  val awlen   = out(8)
  val awsize  = out(3)
  val awburst = out(2)
  val awlock  = out()
  val awcache = out(4)
  val awprot  = out(3)
  val awqos   = out(4)
  // Write data channel
  val wvalid  = out()
  val wready  = in()
  val wdata   = out(dataW)
  val wstrb   = out(dataW / 8)
  val wlast   = out()
  // Write response channel
  val bvalid  = in()
  val bready  = out()
  val bid     = in(idW)
  val bresp   = in(2)
  // Read address channel
  val arvalid = out()
  val arready = in()
  val arid    = out(idW)
  val araddr  = out(addrW)
  val arlen   = out(8)
  val arsize  = out(3)
  val arburst = out(2)
  val arlock  = out()
  val arcache = out(4)
  val arprot  = out(3)
  val arqos   = out(4)
  // Read data channel
  val rvalid  = in()
  val rready  = out()
  val rid     = in(idW)
  val rdata   = in(dataW)
  val rresp   = in(2)
  val rlast   = in()
}

